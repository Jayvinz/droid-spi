package top.jayvin.android.spi

/**
 * The interface a compile-time generated provider configuration table implements.
 *
 * It corresponds to the JDK SPI provider-configuration file (`META-INF/services/<service FQN>`):
 * the only change is that "store provider class names in files named after the service" becomes
 * "generate one class with a fixed fully-qualified name at compile time". Provider
 * implementations are still referenced through class literals; runtime never looks providers up
 * by name.
 *
 * The implementation class is generated directly as bytecode by the Gradle plugin with ASM, with
 * the fixed FQN `top.jayvin.android.spi.generated.ServiceConfiguration`. Runtime compiles a direct
 * `new` against a compileOnly placeholder class; at runtime the same-name class generated by the
 * app takes its place.
 *
 * Convention: **provider class literals may only appear inside method bodies**, never in
 * `<clinit>`. That way, while a dynamic module is not installed, only the method throws
 * [NoClassDefFoundError]; the configuration table itself is not marked erroneous, and one more
 * call after the module is installed succeeds.
 *
 * This is the generator-facing contract, not a business-facing facade: the runtime registry
 * catches these errors and reports them as [ProviderState] / null, so code using [ServiceLoader]
 * never observes them.
 */
interface ProviderConfiguration {

    /**
     * Returns every service interface known to the generated table.
     *
     * The array **must contain interfaces only**, and they must live in base / resident modules.
     *
     * @return every service interface known to the generated table
     */
    fun services(): Array<Class<*>>

    /**
     * Returns the variant keys, one-to-one with [services].
     *
     * An empty string means the default variant. The default key may appear more than once for
     * the same service (several default implementations); any other key is unique per service.
     *
     * @return the keys; an empty string means the default variant
     */
    fun keys(): Array<String>

    /**
     * Resolves the provider class at [index] without initializing it.
     *
     * [index] is the position in the [services] / [keys] arrays. Used to determine whether a
     * provider is ready and to enumerate every entry, including multiple default providers.
     *
     * @param index the entry position
     * @return the provider class, or null when [index] is out of range
     * @throws NoClassDefFoundError when the provider class exists in the table but is not
     *   visible to the current process (for example, its dynamic module is not installed)
     */
    fun providerAt(index: Int): Class<*>?

    /**
     * Instantiates the provider at [index] (using the `@ProviderFactory` static factory when
     * present), triggering the provider's `<clinit>`.
     *
     * @param index the entry position
     * @return a new provider instance, or null when [index] is out of range
     * @throws ExceptionInInitializerError when the provider's `<clinit>` fails (irreversible
     *   in this process)
     * @throws NoClassDefFoundError when the provider class is not visible to the current process
     */
    fun newProviderAt(index: Int): Any?
}
