import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.library")
    id("maven-publish")
    id("framework-publishing")
}

android {
    namespace = "top.jayvin.android.spi"
    compileSdk = 35

    defaultConfig {
        minSdk = 24
        consumerProguardFiles("consumer-rules.pro")
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        // Facade tests run on the JVM; android.util.Log calls are no-ops there.
        unitTests.isReturnDefaultValues = true
    }

    publishing {
        singleVariant("release") {
            withSourcesJar()
        }
    }
}

// AGP 9 compiles Kotlin itself (built-in Kotlin); the Kotlin Android plugin is unnecessary.
kotlin {
    compilerOptions {
        jvmTarget.set(JvmTarget.JVM_17)
        // Consumers on the AGP 8.x lines often still use Kotlin 2.0/2.1, which cannot read
        // 2.4 metadata. The runtime API surface is plain Kotlin, so emit 2.0 metadata and
        // restrict the API/language level to 2.0 to keep the published AAR consumable.
        languageVersion.set(org.jetbrains.kotlin.gradle.dsl.KotlinVersion.KOTLIN_2_0)
        apiVersion.set(org.jetbrains.kotlin.gradle.dsl.KotlinVersion.KOTLIN_2_0)
        freeCompilerArgs.add("-Xmetadata-version=2.0.0")
    }
}

dependencies {
    // Declaring stdlib explicitly also stops AGP from publishing its bundled 2.4.x version as a
    // compile dependency, which would drag every consumer onto Kotlin 2.4.
    api("org.jetbrains.kotlin:kotlin-stdlib:2.0.21")
    // Compile-time placeholder: at runtime the same-name ServiceConfiguration generated by the app plugin takes its place
    compileOnly(project(":configuration-stub"))
    testImplementation("junit:junit:4.13.2")
}

// Maven Central requires a javadoc jar. AGP has no javadoc variant for Android libraries, so this
// publishes the project README as documentation instead of an empty artifact.
val javadocJar = tasks.register<Jar>("javadocJar") {
    archiveClassifier.set("javadoc")
    from(layout.projectDirectory.dir("..").file("README.md"))
}

afterEvaluate {
    publishing {
        publications {
            create<MavenPublication>("release") {
                from(components["release"])
                artifact(javadocJar)
            }
        }
    }
}
