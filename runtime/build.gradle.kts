plugins {
    id("com.android.library")
    id("org.jetbrains.kotlin.android")
    id("maven-publish")
    id("framework-publishing")
}

android {
    namespace = "top.jayvin.android.spi"
    compileSdk = 35

    defaultConfig {
        minSdk = 24
        consumerProguardFiles("consumer-rules.pro")
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    testOptions {
        // Facade tests run on the JVM; android.util.Log calls are no-ops there.
        unitTests.isReturnDefaultValues = true
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    publishing {
        singleVariant("release") {
            withSourcesJar()
        }
    }
}

dependencies {
    // Compile-time placeholder: at runtime the same-name ServiceConfiguration generated by the app plugin takes its place
    compileOnly(project(":configuration-stub"))
    testImplementation("junit:junit:4.13.2")
}

// Maven Central requires a javadoc jar. AGP has no javadoc variant for Android libraries, so this
// publishes the project README as documentation instead of an empty artifact.
val javadocJar by tasks.registering(Jar::class) {
    archiveClassifier.set("javadoc")
    from(layout.projectDirectory.dir("..").file("README.md"))
}

afterEvaluate {
    publishing {
        publications {
            create<MavenPublication>("release") {
                artifactId = "droidspi-runtime"
                from(components["release"])
                artifact(javadocJar)
            }
        }
    }
}
